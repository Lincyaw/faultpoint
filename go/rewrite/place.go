const (
	pointsPackage = "faultpoint/fppoints"
	codeWidth     = 120
	// genericsVersion is the first Go version with generics, which a call handed to fppoints.Call needs.
	genericsVersion = "go1.18"
	// undeclaredVersion is the Go version the go command compiles a module at whose go.mod has no go directive.
	undeclaredVersion = "go1.16"
)

var errorType = types.Universe.Lookup("error").Type()

// checkActions are the actions of a call point kept at its check, where the call has already run and cannot be
// skipped by fail.
var checkActions = []string{"fail_after", "delay", "crash"}

var registryTemplate = template.Must(template.New("registry").Parse(`// Code generated by fprewrite. DO NOT EDIT.

package {{.Name}}

import {{printf "%q" .Core}}

func init() {
{{- range .Errors}}
	{{$.CoreName}}.RegisterError({{printf "%q" .Name}}, {{.Variable}})
{{- end}}
{{- range .Restricted}}
	{{$.CoreName}}.Restrict({{printf "%q" .ID}}{{range .Actions}}, {{printf "%q" .}}{{end}})
{{- end}}
}
`))

// Placement switches each placement rule and replaces its name lists, under "placement" in the configuration; its
// scope adds the dependency packages whose code gets points besides the local modules.
type Placement struct {
	Branch  bool         `json:"branch"`
	Call    bool         `json:"call"`
	Check   bool         `json:"check"`
	Loop    bool         `json:"loop"`
	Clock   []string     `json:"clock"`
	Errors  bool         `json:"errors"`
	Scope   []ScopeEntry `json:"scope"`
	Exclude []string     `json:"exclude"`
	// ErrorPackages are packages, such as context or io, whose exported error variables the build registers, so that
	// an observation names context.Canceled rather than its type.
	ErrorPackages []string `json:"error_packages"`
}

// ScopeEntry names a dependency package path, which includes the packages under it, limited to some kinds when
// Kinds is given.
type ScopeEntry struct {
	Include string   `json:"include"`
	Kinds   []string `json:"kinds"`
}

// limitedTo is the placement of a dependency whose scope entry allows only some kinds; the error registry serves
// call points.
func (p Placement) limitedTo(kinds []string) Placement {
	if kinds == nil {
		return p
	}
	limited := p
	limited.Branch = p.Branch && slices.Contains(kinds, "branch")
	limited.Call = p.Call && slices.Contains(kinds, "call")
	limited.Check = p.Check && slices.Contains(kinds, "check")
	limited.Loop = p.Loop && slices.Contains(kinds, "loop")
	limited.Errors = p.Errors && slices.Contains(kinds, "call")
	if !slices.Contains(kinds, "clock") {
		limited.Clock = nil
	}
	return limited
}

// PointEntry is one point of the manifest, as spec/manifest.schema.json defines it.
type PointEntry struct {
	ID       string `json:"id"`
	Kind     string `json:"kind"`
	File     string `json:"file"`
	Line     int    `json:"line"`
	Function string `json:"function"`
	Code     string `json:"code"`
	// Actions are the actions the point implements when narrower than its kind's, nil for all of its kind's.
	Actions []string `json:"actions,omitempty"`
}

// Manifest lists every point placed in a service and the error names its build registers, which a fail rule may
// name.
type Manifest struct {
	Service  string       `json:"service"`
	Language string       `json:"language"`
	Points   []PointEntry `json:"points"`
	Errors   []string     `json:"errors"`
}

// qualifiedName is path.Name of a named type, or empty for any other type.
func qualifiedName(typ types.Type) string {
	named, ok := types.Unalias(typ).(*types.Named)
	if !ok || named.Obj().Pkg() == nil {
		return ""
	}
	return named.Obj().Pkg().Path() + "." + named.Obj().Name()
}

// sdkCall is a call of a function of an SDK package, which a rewritten file imports under its last path element.
func sdkCall(pkg, function string, arguments ...ast.Expr) *ast.CallExpr {
	return &ast.CallExpr{Fun: &ast.SelectorExpr{X: ast.NewIdent(path.Base(pkg)), Sel: ast.NewIdent(function)}, Args: arguments}
}

type function struct {
	name     string
	context  func() ast.Expr
	check    string
	literals int
}

// placer places the points of one file, in the same way for a copy and for a scan, so that their ids agree.
type placer struct {
	service   string
	path      string
	version   string
	placement Placement
	fset      *token.FileSet
	info      *types.Info
	file      *ast.File
	functions []*function
	anchors   map[ast.Node]string
	ordinals  map[string]int
	points    []PointEntry
}

// placePoints places the points of a file in its syntax tree and returns them.
func placePoints(service, relative string, placement Placement, pkg *packages.Package, file *ast.File) []PointEntry {
	p := &placer{service: service, path: relative, version: undeclaredVersion, placement: placement, fset: pkg.Fset,
		info: pkg.TypesInfo, file: file, anchors: map[ast.Node]string{}, ordinals: map[string]int{}}
	// go/packages type-checks a module without a go directive at the toolchain's version, not at the one it compiles at.
	if pkg.Module.GoVersion != "" {
		p.version = "go" + pkg.Module.GoVersion
	}
	astutil.Apply(file, p.pre, p.post)
	return p.points
}

func (p *placer) text(node ast.Node) string {
	var buffer bytes.Buffer
	if err := printer.Fprint(&buffer, p.fset, node); err != nil {
		log.Fatal(err)
	}
	return buffer.String()
}

func (p *placer) current() *function { return p.functions[len(p.functions)-1] }

func (p *placer) functionName() string {
	if len(p.functions) == 0 {
		return "<package>"
	}
	return p.current().name
}

// record adds a point to the manifest and returns its id.
func (p *placer) record(id, kind string, node ast.Node, code string) string {
	code = strings.SplitN(code, "\n", 2)[0]
	if len(code) > codeWidth {
		code = code[:codeWidth]
	}
	p.points = append(p.points, PointEntry{ID: id, Kind: kind, File: p.path,
		Line: p.fset.Position(node.Pos()).Line, Function: p.functionName(), Code: code})
	return id
}

// place records a point anchored at a node: the hash of the node's printed form, numbered when the function
// repeats it for the same kind, so that an unrelated edit does not change the id.
func (p *placer) place(kind string, node ast.Node, anchor string) string {
	digest := sha256.Sum256([]byte(anchor))
	id := p.service + ":" + kind + ":" + p.path + ":" + p.functionName() + "#" + hex.EncodeToString(digest[:])[:8]
	ordinal := p.ordinals[id]
	p.ordinals[id]++
	if ordinal > 0 {
		id += "." + strconv.Itoa(ordinal)
	}
	return p.record(id, kind, node, anchor)
}

// contextAccessors are the parameter types a function's points take their context from, with the selectors that
// read it from the parameter, the last one a method called: the request context of a handler of net/http or gin, or
// a context.Context itself.
var contextAccessors = map[string][]string{
	"context.Context":                   nil,
	"*net/http.Request":                 {"Context"},
	"*github.com/gin-gonic/gin.Context": {"Request", "Context"},
}

// contextOf is the context a function's points use: the context of its first parameter of a type of
// contextAccessors, the enclosing function's, or nil.
func (p *placer) contextOf(parameters *ast.FieldList) func() ast.Expr {
	for _, field := range parameters.List {
		for _, name := range field.Names {
			typeName := types.TypeString(p.info.TypeOf(name), func(pkg *types.Package) string { return pkg.Path() })
			if selectors, found := contextAccessors[typeName]; found && name.Name != "_" {
				identifier := name.Name
				return func() ast.Expr {
					var context ast.Expr = ast.NewIdent(identifier)
					for _, selector := range selectors {
						context = &ast.SelectorExpr{X: context, Sel: ast.NewIdent(selector)}
					}
					if len(selectors) > 0 {
						context = &ast.CallExpr{Fun: context}
					}
					return context
				}
			}
		}
	}
	if len(p.functions) > 0 {
		return p.current().context
	}
	return func() ast.Expr { return ast.NewIdent("nil") }
}

// ownReturns are the return statements of a function body, not of the literals it holds.
func ownReturns(body *ast.BlockStmt) []*ast.ReturnStmt {
	var returns []*ast.ReturnStmt
	ast.Inspect(body, func(node ast.Node) bool {
		switch statement := node.(type) {
		case *ast.FuncLit:
			return false
		case *ast.ReturnStmt:
			returns = append(returns, statement)
		}
		return true
	})
	return returns
}

// checkable is whether a function's only result is an unnamed bool that some return computes.
func (p *placer) checkable(signature *ast.FuncType, body *ast.BlockStmt) bool {
	results := signature.Results
	if body == nil || results == nil || len(results.List) != 1 || len(results.List[0].Names) > 0 {
		return false
	}
	if !types.Identical(p.info.TypeOf(results.List[0].Type), types.Typ[types.Bool]) {
		return false
	}
	return slices.ContainsFunc(ownReturns(body), func(statement *ast.ReturnStmt) bool {
		return len(statement.Results) == 1 && p.info.Types[statement.Results[0]].Value == nil
	})
}

func (p *placer) enter(name string, signature *ast.FuncType, body *ast.BlockStmt, node ast.Node) {
	entered := &function{name: name, context: p.contextOf(signature.Params)}
	p.functions = append(p.functions, entered)
	if p.placement.Check && p.checkable(signature, body) {
		entered.check = p.record(p.service+":check:"+p.path+":"+name, "check", node, p.text(signature))
	}
}

func (p *placer) call(name string, point string, arguments ...ast.Expr) *ast.CallExpr {
	return sdkCall(pointsPackage, name,
		append([]ast.Expr{p.current().context(), &ast.BasicLit{Kind: token.STRING, Value: strconv.Quote(point)}}, arguments...)...)
}

// errorVariable is the variable of an `err != nil` condition whose type is exactly error.
func (p *placer) errorVariable(condition ast.Expr) *ast.Ident {
	binary, ok := condition.(*ast.BinaryExpr)
	if !ok || binary.Op != token.NEQ {
		return nil
	}
	variable, ok := binary.X.(*ast.Ident)
	if !ok || !p.info.Types[binary.Y].IsNil() || !types.Identical(p.info.TypeOf(variable), errorType) {
		return nil
	}
	return variable
}

// guardsError is whether a block returns a non-nil error directly.
func (p *placer) guardsError(body *ast.BlockStmt) bool {
	return slices.ContainsFunc(body.List, func(statement ast.Stmt) bool {
		returned, ok := statement.(*ast.ReturnStmt)
		if !ok || len(returned.Results) == 0 {
			return false
		}
		value := p.info.Types[returned.Results[len(returned.Results)-1]]
		return !value.IsNil() && value.Type != nil && types.Implements(value.Type, errorType.Underlying().(*types.Interface))
	})
}

func (p *placer) constantLoop(node ast.Node) bool {
	switch loop := node.(type) {
	case *ast.ForStmt:
		binary, ok := loop.Cond.(*ast.BinaryExpr)
		return ok && p.info.Types[binary.Y].Value != nil
	case *ast.RangeStmt:
		return p.info.Types[loop.X].Value != nil
	}
	return false
}

// clockCall is whether a call reads the clock through a function of the placement's clock list, which must
// return a time.Time.
func (p *placer) clockCall(call *ast.CallExpr) bool {
	callee, ok := typeutil.Callee(p.info, call).(*types.Func)
	if !ok || !slices.Contains(p.placement.Clock, callee.FullName()) {
		return false
	}
	results := callee.Type().(*types.Signature).Results()
	if results.Len() != 1 || qualifiedName(results.At(0).Type()) != "time.Time" {
		log.Fatalf("clock function %s does not return a time.Time", callee.FullName())
	}
	return true
}

func (p *placer) pre(cursor *astutil.Cursor) bool {
	switch node := cursor.Node().(type) {
	case *ast.FuncDecl:
		name := node.Name.Name
		if node.Recv != nil && len(node.Recv.List) == 1 {
			name = strings.TrimLeft(p.text(node.Recv.List[0].Type), "*") + "." + name
		}
		p.enter(name, node.Type, node.Body, node)
	case *ast.FuncLit:
		outer := "<package>"
		if len(p.functions) > 0 {
			p.current().literals++
			outer = p.current().name + ".func" + strconv.Itoa(p.current().literals)
		}
		p.enter(outer, node.Type, node.Body, node)
	case *ast.IfStmt:
		p.anchors[node] = p.text(node.Cond)
	case *ast.ForStmt, *ast.RangeStmt, *ast.CallExpr:
		p.anchors[node] = p.text(node)
	}
	return true
}

// post places the points of a node after its children; a clock read in a package-level initializer is left alone.
func (p *placer) post(cursor *astutil.Cursor) bool {
	switch node := cursor.Node().(type) {
	case *ast.FuncDecl, *ast.FuncLit:
		p.functions = p.functions[:len(p.functions)-1]
	case *ast.ReturnStmt:
		if p.current().check != "" && len(node.Results) == 1 {
			node.Results[0] = p.call("Check", p.current().check, node.Results[0])
		}
	case *ast.IfStmt:
		p.placeCondition(cursor, node)
	case *ast.ForStmt:
		p.placeLoop(node, node.Body)
	case *ast.RangeStmt:
		p.placeLoop(node, node.Body)
	case *ast.CallExpr:
		if len(p.functions) > 0 && p.clockCall(node) {
			cursor.Replace(p.call("Clock", p.place("clock", node, p.anchors[node]), node))
		}
	}
	return true
}

// placeCondition makes `err != nil` a call point and any other condition guarding an error return a branch point.
// The call point goes to the call that produced err when it can be skipped there, so that fail does not run it, and
// otherwise to the check, which can only replace err once the call has run.
func (p *placer) placeCondition(cursor *astutil.Cursor, node *ast.IfStmt) {
	variable := p.errorVariable(node.Cond)
	switch {
	case variable != nil && p.placement.Call:
		point := p.place("call", node, p.anchors[node])
		if call := p.producingCall(cursor, node, variable); call != nil {
			call.Fun = p.call("Call", point, call.Fun)
		} else {
			p.points[len(p.points)-1].Actions = checkActions
			node.Cond = p.call("Failed", point, &ast.UnaryExpr{Op: token.AND, X: ast.NewIdent(variable.Name)})
		}
	case variable == nil && p.placement.Branch && p.guardsError(node.Body):
		node.Cond = p.call("Branch", p.place("branch", node, p.anchors[node]), node.Cond)
	}
}

// producingCall is the call whose error an `err != nil` checks, when the call can be handed to fppoints.Call: the
// module's Go version has generics, and the only value of the producing assignment is a call of a function or method
// value named without side effects, which is no conversion, builtin or inferred generic instance, whose last result
// is the error, and which the boundary wiring leaves alone. It is nil otherwise. A chained call, as in
// QueryRow(...).Scan, stays at its check: the call before it may have done the work, which skipping the last one
// would not undo.
func (p *placer) producingCall(cursor *astutil.Cursor, node *ast.IfStmt, variable *ast.Ident) *ast.CallExpr {
	if version.Compare(p.version, genericsVersion) < 0 {
		return nil
	}
	assignment := p.producingAssignment(cursor, node, p.info.ObjectOf(variable))
	if assignment == nil || len(assignment.Rhs) != 1 {
		return nil
	}
	call, isCall := assignment.Rhs[0].(*ast.CallExpr)
	if !isCall {
		return nil
	}
	signature, isSignature := p.info.TypeOf(call.Fun).(*types.Signature)
	if !isSignature || p.info.Types[call.Fun].IsType() || p.info.Types[call.Fun].IsBuiltin() || !plainValue(call.Fun) {
		return nil
	}
	results := signature.Results()
	if results.Len() != len(assignment.Lhs) || !types.Identical(results.At(results.Len()-1).Type(), errorType) {
		return nil
	}
	named := call.Fun
	if selector, isSelector := named.(*ast.SelectorExpr); isSelector {
		named = selector.Sel
	}
	if _, generic := p.info.Instances[named.(*ast.Ident)]; generic || wired(p.info, call) {
		return nil
	}
	return call
}

// producingAssignment is the assignment whose error an `err != nil` checks: the nearest one whose last target is err,
// in the if's init or among the statements before the if in its block, when no statement between may assign err.
// A statement between must not assign err, range into it or take its address, nor bear a label a goto could enter
// by, and when there is one, err must not escape, so that none of the calls between can assign it.
func (p *placer) producingAssignment(cursor *astutil.Cursor, node *ast.IfStmt, variable types.Object) *ast.AssignStmt {
	var statements []ast.Stmt
	switch parent := cursor.Parent().(type) {
	case *ast.BlockStmt:
		statements = parent.List[:cursor.Index()]
	case *ast.CaseClause:
		statements = parent.Body[:cursor.Index()]
	case *ast.CommClause:
		statements = parent.Body[:cursor.Index()]
	}
	if node.Init != nil {
		statements = append(slices.Clone(statements), node.Init)
	}
	for index := len(statements) - 1; index >= 0; index-- {
		assignment, isAssignment := statements[index].(*ast.AssignStmt)
		_, labeled := statements[index].(*ast.LabeledStmt)
		switch {
		case isAssignment && p.refersTo(assignment.Lhs[len(assignment.Lhs)-1], variable):
			return assignment
		// Whether err escapes is asked once, at the first statement between.
		case labeled || p.assigns(statements[index], variable) || (index == len(statements)-1 && p.escapes(variable)):
			return nil
		}
	}
	return nil
}

// refersTo is whether an expression is an identifier of a variable, in parentheses or not.
func (p *placer) refersTo(expression ast.Expr, variable types.Object) bool {
	identifier, isIdentifier := ast.Unparen(expression).(*ast.Ident)
	return isIdentifier && p.info.ObjectOf(identifier) == variable
}

// assigns is whether a node may assign a variable: it assigns it, ranges into it or takes its address, if only in a
// function literal.
func (p *placer) assigns(node ast.Node, variable types.Object) bool {
	found := false
	ast.Inspect(node, func(inner ast.Node) bool {
		var targets []ast.Expr
		switch inner := inner.(type) {
		case *ast.AssignStmt:
			targets = inner.Lhs
		case *ast.RangeStmt:
			targets = []ast.Expr{inner.Key, inner.Value}
		case *ast.UnaryExpr:
			if inner.Op == token.AND {
				targets = []ast.Expr{inner.X}
			}
		}
		found = found || slices.ContainsFunc(targets, func(target ast.Expr) bool { return p.refersTo(target, variable) })
		return !found
	})
	return found
}

// escapes is whether code away from the statements that name a variable may assign it: it is a package variable, the
// file takes its address, or a function literal it is declared outside of assigns it.
func (p *placer) escapes(variable types.Object) bool {
	escapes := variable.Parent() == variable.Pkg().Scope()
	ast.Inspect(p.file, func(node ast.Node) bool {
		switch node := node.(type) {
		case *ast.FuncLit:
			outside := variable.Pos() < node.Pos() || variable.Pos() >= node.End()
			escapes = escapes || (outside && p.assigns(node.Body, variable))
		case *ast.UnaryExpr:
			escapes = escapes || (node.Op == token.AND && p.refersTo(node.X, variable))
		}
		return !escapes
	})
	return escapes
}

// plainValue is whether an expression names a value without evaluating anything that could have an effect: an
// identifier or a selector of one, as in f, pkg.F or s.store.Reserve.
func plainValue(expression ast.Expr) bool {
	switch value := expression.(type) {
	case *ast.Ident:
		return value.Name != "_"
	case *ast.SelectorExpr:
		return plainValue(value.X)
	}
	return false
}

func (p *placer) placeLoop(node ast.Node, body *ast.BlockStmt) {
	if !p.placement.Loop || p.constantLoop(node) {
		return
	}
	point := p.place("loop", node, p.anchors[node])
	body.List = append([]ast.Stmt{&ast.ExprStmt{X: p.call("Loop", point)}}, body.List...)
}

// registeredError is an error variable of a package with the name a registry registers it under.
type registeredError struct {
	Name     string
	Package  string
	Variable string
}

// packageErrors are the exported error variables of the packages a placement's error_packages names, loaded as the
// go command resolves them from a directory.
func packageErrors(dir string, paths []string) []registeredError {
	if len(paths) == 0 {
		return nil
	}
	loaded, err := packages.Load(&packages.Config{Dir: dir, Mode: packages.NeedName | packages.NeedTypes}, paths...)
	if err != nil {
		log.Fatal(err)
	}
	if packages.PrintErrors(loaded) > 0 {
		os.Exit(1)
	}
	var errors []registeredError
	for _, pkg := range loaded {
		scope := pkg.Types.Scope()
		for _, variable := range scope.Names() {
			found, ok := scope.Lookup(variable).(*types.Var)
			if ok && token.IsExported(variable) && types.Identical(found.Type(), errorType) {
				errors = append(errors, registeredError{Name: pkg.PkgPath + "." + variable, Package: pkg.PkgPath, Variable: variable})
			}
		}
	}
	return errors
}

// packageRegistry is the source of a file that registers with the core, from a package's init, those of its points
// that implement fewer actions than their kind and, when the placement registers errors, its error variables by
// name, which a call fail rule returns and an observation names errors by; it returns the error names too, and nil
// when there is nothing to register.
func packageRegistry(pkg *packages.Package, placement Placement, points []PointEntry) ([]byte, []string) {
	scope := pkg.Types.Scope()
	var errors []registeredError
	var names []string
	for _, variable := range scope.Names() {
		found, ok := scope.Lookup(variable).(*types.Var)
		if ok && placement.Errors && types.Identical(found.Type(), errorType) {
			errors = append(errors, registeredError{Name: pkg.PkgPath + "." + variable, Variable: variable})
			names = append(names, pkg.PkgPath+"."+variable)
		}
	}
	restricted := slices.DeleteFunc(slices.Clone(points), func(entry PointEntry) bool { return entry.Actions == nil })
	if len(errors) == 0 && len(restricted) == 0 {
		return nil, nil
	}
	var source bytes.Buffer
	err := registryTemplate.Execute(&source, map[string]any{"Name": pkg.Name, "Errors": errors,
		"Restricted": restricted, "Core": corePackage, "CoreName": path.Base(corePackage)})
	if err != nil {
		log.Fatal(err)
	}
	formatted, err := format.Source(source.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	return formatted, names
}
