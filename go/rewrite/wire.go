// pluginPackages are the packages of the plugins a configuration can enable.
var pluginPackages = map[string]string{pointsPlugin: pointsPackage, httpPlugin: httpPackage, sqlPlugin: sqlPackage,
	pgxPlugin: pgxPackage, redisPlugin: redisPackage}

// wrapper is the adapter function the copy applies to a value it hands to a library, or to a value a library returns.
type wrapper struct {
	plugin   string
	pkg      string
	function string
}

var (
	handlerWrapper    = wrapper{plugin: httpPlugin, pkg: httpPackage, function: "Handler"}
	transportWrapper  = wrapper{plugin: httpPlugin, pkg: httpPackage, function: "Transport"}
	driverNameWrapper = wrapper{plugin: sqlPlugin, pkg: sqlPackage, function: "DriverName"}
	redisWrapper      = wrapper{plugin: redisPlugin, pkg: redisPackage, function: "Instrument"}
)

// argumentWrappers wrap one argument of a call: the handler a server serves and the driver sql.Open opens.
var argumentWrappers = map[string]struct {
	index   int
	wrapper wrapper
}{
	"net/http.ListenAndServe":    {index: 1, wrapper: handlerWrapper},
	"net/http.ListenAndServeTLS": {index: 3, wrapper: handlerWrapper},
	"net/http.Serve":             {index: 1, wrapper: handlerWrapper},
	"net/http.ServeTLS":          {index: 3, wrapper: handlerWrapper},
	"database/sql.Open":          {index: 0, wrapper: driverNameWrapper},
}

// resultWrappers wrap what a call returns: the go-redis clients, which take a hook.
var resultWrappers = map[string]wrapper{
	redisModule + ".NewClient":          redisWrapper,
	redisModule + ".NewFailoverClient":  redisWrapper,
	redisModule + ".NewUniversalClient": redisWrapper,
	redisModule + ".NewClusterClient":   redisWrapper,
}

// methodWrappers replace a method call by an adapter function that takes the receiver first, for a library whose
// results the adapter must replace; a call matches by the method's name and signature, whatever its receiver, so
// that calls through an application's own interfaces of these methods are wired too.
var methodWrappers = map[string]struct {
	signature string
	wrapper   wrapper
}{
	"Exec": {signature: "func(context.Context, string, ...any) (" + pgxModule + "/pgconn.CommandTag, error)",
		wrapper: wrapper{plugin: pgxPlugin, pkg: pgxPackage, function: "Exec"}},
	"Query": {signature: "func(context.Context, string, ...any) (" + pgxModule + ".Rows, error)",
		wrapper: wrapper{plugin: pgxPlugin, pkg: pgxPackage, function: "Query"}},
	"QueryRow": {signature: "func(context.Context, string, ...any) " + pgxModule + ".Row",
		wrapper: wrapper{plugin: pgxPlugin, pkg: pgxPackage, function: "QueryRow"}},
	"SendBatch": {signature: "func(context.Context, *" + pgxModule + ".Batch) " + pgxModule + ".BatchResults",
		wrapper: wrapper{plugin: pgxPlugin, pkg: pgxPackage, function: "SendBatch"}},
	"Begin": {signature: "func(context.Context) (" + pgxModule + ".Tx, error)",
		wrapper: wrapper{plugin: pgxPlugin, pkg: pgxPackage, function: "Begin"}},
	"BeginTx": {signature: "func(context.Context, " + pgxModule + ".TxOptions) (" + pgxModule + ".Tx, error)",
		wrapper: wrapper{plugin: pgxPlugin, pkg: pgxPackage, function: "BeginTx"}},
}

// fieldWrappers wrap one field of a struct, in its literals and assignments: a server's handler and a client's
// transport, where nil keeps its meaning of the default.
var fieldWrappers = map[string]struct {
	field   string
	wrapper wrapper
}{
	"net/http.Server": {field: "Handler", wrapper: handlerWrapper},
	"net/http.Client": {field: "Transport", wrapper: transportWrapper},
}

var initTemplate = template.Must(template.New("init").Parse(`// Code generated by fprewrite. DO NOT EDIT.

package {{.Name}}

import (
{{- range .Imports}}
	{{.}}
{{- end}}
)

func init() {
{{- if .HTTP}}
	http.DefaultClient.Transport = fphttp.Transport(http.DefaultClient.Transport)
{{- end}}
	faultpoint.Start()
}
`))

// wirer routes the values a file hands to libraries, and the calls it makes on them, through the adapters of the
// enabled plugins.
type wirer struct {
	info    *types.Info
	plugins []string
	imports map[string]bool
}

// wireBoundaries wires the boundaries of a file and returns the adapter packages it now imports.
func wireBoundaries(info *types.Info, plugins []string, file *ast.File) []string {
	w := &wirer{info: info, plugins: plugins, imports: map[string]bool{}}
	astutil.Apply(file, nil, w.post)
	return slices.Sorted(maps.Keys(w.imports))
}

func (w *wirer) wrap(target wrapper, value ast.Expr) ast.Expr {
	w.imports[target.pkg] = true
	return sdkCall(target.pkg, target.function, value)
}

func (w *wirer) post(cursor *astutil.Cursor) bool {
	switch node := cursor.Node().(type) {
	case *ast.CallExpr:
		w.wireArgument(node)
		w.wireMethod(node)
		w.wireResult(cursor, node)
	case *ast.CompositeLit:
		w.wireLiteral(node)
	case *ast.AssignStmt:
		w.wireAssignment(node)
	}
	return true
}

func (w *wirer) wireArgument(call *ast.CallExpr) {
	callee, ok := typeutil.Callee(w.info, call).(*types.Func)
	if !ok {
		return
	}
	target, found := argumentWrappers[callee.FullName()]
	if found && slices.Contains(w.plugins, target.wrapper.plugin) && len(call.Args) > target.index {
		call.Args[target.index] = w.wrap(target.wrapper, call.Args[target.index])
	}
}

func (w *wirer) wireResult(cursor *astutil.Cursor, call *ast.CallExpr) {
	callee, ok := typeutil.Callee(w.info, call).(*types.Func)
	if !ok {
		return
	}
	if target, found := resultWrappers[callee.FullName()]; found && slices.Contains(w.plugins, target.plugin) {
		cursor.Replace(w.wrap(target, call))
	}
}

// wireMethod turns x.M(arguments) into adapter.M(x, arguments), taking the address of x where Go took it implicitly
// for a pointer receiver.
func (w *wirer) wireMethod(call *ast.CallExpr) {
	selector, isSelector := call.Fun.(*ast.SelectorExpr)
	if !isSelector || w.info.Selections[selector] == nil || w.info.Selections[selector].Kind() != types.MethodVal {
		return
	}
	selection := w.info.Selections[selector]
	target, found := methodWrappers[selector.Sel.Name]
	if !found || !slices.Contains(w.plugins, target.wrapper.plugin) || signatureText(selection.Type().(*types.Signature)) != target.signature {
		return
	}
	receiver := selector.X
	_, pointerReceiver := selection.Obj().Type().(*types.Signature).Recv().Type().(*types.Pointer)
	_, pointerValue := types.Unalias(selection.Recv()).(*types.Pointer)
	if pointerReceiver && !pointerValue {
		receiver = &ast.UnaryExpr{Op: token.AND, X: receiver}
	}
	w.imports[target.wrapper.pkg] = true
	call.Fun = sdkCall(target.wrapper.pkg, target.wrapper.function).Fun
	call.Args = append([]ast.Expr{receiver}, call.Args...)
}

// signatureText is a signature without parameter names, its types qualified by package path.
func signatureText(signature *types.Signature) string {
	unnamed := func(tuple *types.Tuple) *types.Tuple {
		parameters := make([]*types.Var, tuple.Len())
		for index := range parameters {
			parameters[index] = types.NewParam(token.NoPos, nil, "", tuple.At(index).Type())
		}
		return types.NewTuple(parameters...)
	}
	bare := types.NewSignatureType(nil, nil, nil, unnamed(signature.Params()), unnamed(signature.Results()), signature.Variadic())
	return types.TypeString(bare, func(pkg *types.Package) string { return pkg.Path() })
}

// wireLiteral wraps the field of a keyed literal, adding it as nil when the literal leaves it out.
func (w *wirer) wireLiteral(literal *ast.CompositeLit) {
	target, found := fieldWrappers[qualifiedName(w.info.TypeOf(literal))]
	keyed := !slices.ContainsFunc(literal.Elts, func(element ast.Expr) bool {
		_, pair := element.(*ast.KeyValueExpr)
		return !pair
	})
	if !found || !keyed || !slices.Contains(w.plugins, target.wrapper.plugin) {
		return
	}
	index := slices.IndexFunc(literal.Elts, func(element ast.Expr) bool {
		key, named := element.(*ast.KeyValueExpr).Key.(*ast.Ident)
		return named && key.Name == target.field
	})
	if index < 0 {
		literal.Elts = append(literal.Elts, &ast.KeyValueExpr{Key: ast.NewIdent(target.field), Value: ast.NewIdent("nil")})
		index = len(literal.Elts) - 1
	}
	pair := literal.Elts[index].(*ast.KeyValueExpr)
	pair.Value = w.wrap(target.wrapper, pair.Value)
}

func (w *wirer) wireAssignment(assignment *ast.AssignStmt) {
	if assignment.Tok != token.ASSIGN || len(assignment.Lhs) != len(assignment.Rhs) {
		return
	}
	for index, left := range assignment.Lhs {
		selector, ok := left.(*ast.SelectorExpr)
		if !ok || w.info.Selections[selector] == nil || w.info.Selections[selector].Kind() != types.FieldVal {
			continue
		}
		receiver := w.info.Selections[selector].Recv()
		if pointer, isPointer := types.Unalias(receiver).(*types.Pointer); isPointer {
			receiver = pointer.Elem()
		}
		target, found := fieldWrappers[qualifiedName(receiver)]
		if found && target.field == selector.Sel.Name && slices.Contains(w.plugins, target.wrapper.plugin) {
			assignment.Rhs[index] = w.wrap(target.wrapper, assignment.Rhs[index])
		}
	}
}

// packageInit is the source of the file every rewritten package gets: it registers the enabled plugins,
// instruments http.DefaultClient and starts the core, which happens once, after every plugin has registered, in
// whichever rewritten package initializes first, also in a test binary.
func packageInit(name string, plugins []string) []byte {
	imports := []string{strconv.Quote(corePackage), "_ " + strconv.Quote(contextPackage)}
	for _, plugin := range plugins {
		if plugin == httpPlugin {
			imports = append(imports, strconv.Quote("net/http"), strconv.Quote(httpPackage))
		} else {
			imports = append(imports, "_ "+strconv.Quote(pluginPackages[plugin]))
		}
	}
	var source bytes.Buffer
	err := initTemplate.Execute(&source, map[string]any{"Name": name, "Imports": imports, "HTTP": slices.Contains(plugins, httpPlugin)})
	if err != nil {
		log.Fatal(err)
	}
	formatted, err := format.Source(source.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	return formatted
}
